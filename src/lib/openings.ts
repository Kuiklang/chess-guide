export function guideFor(name: string): OpeningGuide | undefined {
  return GUIDES.find(([pattern]) => name.includes(pattern))?.[1];
}

/** "Italian Game: Giuoco Piano" -> "อิตาเลียน (Italian Game: Giuoco Piano)" */
export function openingTitle(info: OpeningInfo): string {
  return info.guide ? `${info.guide.th} (${info.name})` : info.name;
}
