// Opening recognition (Lichess chess-openings data, CC0) and Thai explanations of opening ideas.

import { Chess } from 'chess.js';
import { parseUci } from './chessUtil';

export interface OpeningInfo {
  eco: string;
  /** Full English name from the database, e.g. "Italian Game: Giuoco Piano". */
  name: string;
  /** Number of plies that were still "in the book". */
  plies: number;
  guide?: OpeningGuide;
}

export interface OpeningGuide {
  th: string;
  idea: string;
  white: string;
  black: string;
}

type Db = Record<string, [string, string]>;

let dbPromise: Promise<Db> | null = null;

export function loadOpenings(): Promise<Db> {
  if (!dbPromise) {
    dbPromise = fetch(import.meta.env.BASE_URL + 'openings.json')
      .then((r) => (r.ok ? r.json() : {}))
      .catch(() => ({}));
  }
  return dbPromise;
}

function key(fen: string): string {
  return fen.split(' ').slice(0, 3).join(' ');
}

/** Find the deepest named opening reached by a list of UCI moves. */
export function identifyOpening(db: Db, moves: string[]): OpeningInfo | null {
  const game = new Chess();
  let found: OpeningInfo | null = null;
  for (let i = 0; i < Math.min(moves.length, 30); i++) {
    try {
      game.move(parseUci(moves[i]));
    } catch {
      break;
    }
    const hit = db[key(game.fen())];
    if (hit) found = { eco: hit[0], name: hit[1], plies: i + 1, guide: guideFor(hit[1]) };
  }
  return found;
}

